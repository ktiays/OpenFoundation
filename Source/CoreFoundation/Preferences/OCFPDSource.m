        _dirtySourcesLock = OS_UNFAIR_LOCK_INIT;
        _dirtySources = OCFSetCreateMutable(kOCFAllocatorSystemDefault, 0, &kOCFTypeSetCallBacks);
        _synchQueue = dispatch_queue_create_with_target(
