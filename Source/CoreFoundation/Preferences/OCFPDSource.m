// Native deletionStreamCallback, 0x1c02e3eb0. Non-external natively; hidden for the C1 watcher.
// iOS Device divergence: unread. The watcher lock is held across the rebuild, but released before the
// callbacks into each source's lock.
void deletionStreamCallback(
    const struct FSEventStream *stream,
    void *info,
    size_t count,
    void *eventPaths,
    const uint32_t *flags,
    const uint64_t *ids
) {
    (void)stream;
    (void)info;
    (void)ids;
    OCFArrayRef paths = eventPaths;
    dispatch_assert_queue(fseventsQueue);
    os_unfair_lock_lock(&dirWatcherLock);
    OCFMutableArrayRef removed =
        OCFArrayCreateMutable(kOCFAllocatorSystemDefault, 0, &kOCFTypeArrayCallBacks);
    bool recreate = false;
    for (size_t index = 0; index < count; ++index) {
        if ((flags[index] & 0x20200) != 0x20200) {
            continue;
        }
        const void *path = OCFArrayGetValueAtIndex(paths, (OCFIndex)index);
        OCFArrayRef targets = OCFDictionaryGetValue(dirWatcherTargets, path);
        if (targets != NULL) {
            OCFIndex targetCount = OCFArrayGetCount(targets);
            for (OCFIndex target = 0; target < targetCount; ++target) {
                OCFPDSource *source = (OCFPDSource *)OCFArrayGetValueAtIndex(targets, target);
                source->_watchingParentDirectory = NO;
            }
            if (targetCount >= 1) {
                recreate = true;
            }
            OCFArrayAppendArray(removed, targets, (OCFRange){0, targetCount});
        }
        OCFDictionaryRemoveValue(dirWatcherTargets, path);
        OCFArrayRef dirs = watchedDirs;
        OCFIndex position = OCFArrayGetFirstIndexOfValue(dirs, (OCFRange){0, OCFArrayGetCount(dirs)}, path);
        if (position != -1) {
            OCFArrayRemoveValueAtIndex(watchedDirs, position);
        }
    }
    if (recreate) {
        _onqueue_locked_CFPrefsRecreateFileWatcher();
    }
    os_unfair_lock_unlock(&dirWatcherLock);
    OCFIndex removedCount = OCFArrayGetCount(removed);
    for (OCFIndex index = 0; index < removedCount; ++index) {
        OCFPDSource *source = (OCFPDSource *)OCFArrayGetValueAtIndex(removed, index);
        // Native __deletionStreamCallback_block_invoke, 0x1c02e40dc.
        [source lockedSync:^{
          [source clearCacheForReason:OF_STR("directory was deleted")];
        }];
    }
    OCFRelease(removed);
}

