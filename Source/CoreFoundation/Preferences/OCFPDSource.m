// Native _internString, 0x1c02db628, with its statics _internString.lock and _internString.table
// (__DATA,__bss). Non-external.
// NULL stays NULL; kCFPreferencesAnyApplication answers the constant unretained; a tagged pointer or an
// immortal string (retain count 0x0fffffffffffffff) answers itself unretained. Otherwise, under the lock,
// the table (a CFType set, created on first use) supplies the equal string already present, or takes this
// one; the answer is retained after the lock.
static OCFStringRef _internString(OCFStringRef string) {
    static os_unfair_lock lock = OS_UNFAIR_LOCK_INIT;
    static OCFMutableSetRef table;
    if (string == NULL) {
        return NULL;
    }
    OCFStringRef result = kOCFPreferencesAnyApplication;
    if (OCFEqual(string, kOCFPreferencesAnyApplication)) {
        return result;
    }
    if (((uintptr_t)string & 0x8000000000000000) != 0 || OCFGetRetainCount(string) == 0x0FFFFFFFFFFFFFFF) {
        return string;
    }
    os_unfair_lock_lock(&lock);
    if (table == NULL) {
        table = OCFSetCreateMutable(kOCFAllocatorSystemDefault, 0, &kOCFTypeSetCallBacks);
    }
    result = OCFSetGetValue(table, string);
    if (result == NULL) {
        OCFSetAddValue(table, string);
        result = string;
    }
    os_unfair_lock_unlock(&lock);
    OCFRetain(result);
    return result;
}

