        _synchTimer = dispatch_source_create(&intervalSourceType, 10000, 0, _synchQueue);
        dispatch_source_set_event_handler(_synchTimer, ^{
          [[_OCFPrefsSynchronizer sharedInstance] synchronize];
        });
    }
    return self;
}

// Native -[_CFPrefsSynchronizer synchronize], 0x1c0312344. Direct method. Every dirty source of a snapshot
// (taken and cleared under the lock) is written; the snapshot is released.
- (void)synchronize {
    OCFSetRef snapshot = [self copyDirtySourcesSnapshotAndClear];
    OCFSetApplyFunction(snapshot, _CFPrefsSynchronizeDirtySourceForTimer, NULL);
    OCFRelease(snapshot);
}

// Native -[_CFPrefsSynchronizer noteDirtySource:], 0x1c0312380. Direct method.
- (void)noteDirtySource:(id)source {
    os_unfair_lock_lock_with_options(&_dirtySourcesLock, 0x10000);
    OCFSetAddValue(_dirtySources, source);
    if ((_active & 1) == 0) {
        _active = YES;
        dispatch_resume(_synchTimer);
    }
    os_unfair_lock_unlock(&_dirtySourcesLock);
}

// Native -[_CFPrefsSynchronizer copyDirtySourcesSnapshotAndClear], 0x1c03123cc (with
// OUTLINED_FUNCTION_19_3, the lock with options 0x10000). Direct method. Under the lock, a copy (system
// default allocator) of the dirty sources is taken and the synchronizer cleared; +1.
- (OCFSetRef)copyDirtySourcesSnapshotAndClear {
    os_unfair_lock_lock_with_options(&_dirtySourcesLock, 0x10000);
    OCFSetRef snapshot = OCFSetCreateCopy(kOCFAllocatorSystemDefault, _dirtySources);
    [self clear_alreadyLocked];
    os_unfair_lock_unlock(&_dirtySourcesLock);
    return snapshot;
}

// Native -[_CFPrefsSynchronizer clear_alreadyLocked], 0x1c0312418. Direct method. The dirty sources are
// removed; an armed timer is suspended and disarmed.
- (void)clear_alreadyLocked {
    OCFSetRemoveAllValues(_dirtySources);
    if (_active == 1) {
        dispatch_suspend(_synchTimer);
        _active = NO;
    }
}

