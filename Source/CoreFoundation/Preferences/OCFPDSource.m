// into callers. The assertion's native function/file/line are preserved. This local spelling distinguishes
// the inlined copy from the one in cfprefsd.m.
static inline xpc_connection_t connectionForSourceMessage(xpc_object_t message) {
    xpc_connection_t connection = xpc_dictionary_get_remote_connection(message);
    if (connection == NULL) {
        connection = xpc_dictionary_get_value(message, "connection");
        if (connection == NULL || xpc_get_type(connection) != XPC_TYPE_CONNECTION) {
            __assert_rtn(
                "_CFPrefsConnectionForMessage",
                "CFXPreferences_Internal.h",
                427,
                "conn && xpc_get_type(conn) == XPC_TYPE_CONNECTION"
            );
        }
    }
    return connection;
}

static inline audit_token_t auditTokenForSourceMessage(xpc_object_t message) {
    size_t length = 0;
    audit_token_t token = {{0}};
    const void *data = xpc_dictionary_get_data(message, "CFPreferencesAuditToken", &length);
    if (data != NULL && length == sizeof(token)) {
        memcpy(&token, data, sizeof(token));
    } else {
        xpc_connection_get_audit_token(connectionForSourceMessage(message), &token);
    }
    return token;
}

// Native _CFPrefsMessageSenderIsSandboxed, inlined; captured invoke 0x1c02e3ab4, .cold.1 0x1c0314a5c and
// .cold.2 0x1c0314a68. Non-external. An invalid client context leaves the conservative true result.
static inline bool _CFPrefsMessageSenderIsSandboxed(xpc_object_t message) {
    xpc_connection_t connection = connectionForSourceMessage(message);
    __block bool sandboxed = true;
    withClientContext(connection, ^(id object) {
      _OCFPrefsClientContext *context = object;
      bool result;
      if (context->_sandboxed == 0xff) {
          audit_token_t token = auditTokenForSourceMessage(message);
          errno = 0;
          int check = sandbox_check_by_audit_token(token, NULL, SANDBOX_CHECK_NO_REPORT, NULL);
          int error = errno;
          if (check < 0) {
              os_log_error(
                  _CFPrefsDaemonLog(),
                  "sandbox check for (NULL, NULL) on PID %i failed with error: "
                  "%{darwin.errno}d. Treating process as sandboxed",
                  (int)token.val[5],
                  error
              );
          }
          result = check != 0;
          context->_sandboxed = result;
      } else {
          result = context->_sandboxed == 1;
      }
      sandboxed = result;
    });
    return sandboxed;
}

// Native _canDup, 0x1c02e379c, .cold.1 0x1c0314a48. Non-external.
static bool _canDup(void) {
    if (_CFPrefsCurrentProcessIsCFPrefsD()) {
        return true;
    }
    // Native ___canDup_block_invoke, 0x1c02e37e4. Non-external. iOS Device divergence: unread.
    // The assembly passes syscall number 41 in the variadic slot, which Hex-Rays omits.
    // The GOT binding for SANDBOX_CHECK_NO_REPORT at 0x22241b290 has medium confidence.
    dispatch_once(&canDupOnceToken, ^{
      pid_t pid = getpid();
      if (sandbox_check(pid, "syscall-unix", (int)(SANDBOX_CHECK_NO_REPORT | 14), 41) != 0) {
          cannotDuplicate = true;
      }
    });
    return (cannotDuplicate ^ 1) & 1;
}

