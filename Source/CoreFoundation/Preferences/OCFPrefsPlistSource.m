        os_log_error(_CFPrefsClientLog(), "plist diff for %{private}@ was invalid", self);
    } @finally {
        _OCFSetTSD(kLogInProgressSlot, NULL, NULL);
    }
    goto fail;
validate:
    if (xpc_get_type(validation) == XPC_TYPE_DATA) {
        size_t length = xpc_data_get_length(validation);
        if (length <= 0x7ffffffffffffffe) {
            OCFErrorRef parseError = NULL;
            OCFDataRef data = OCFDataCreateWithBytesNoCopy(
                kOCFAllocatorSystemDefault, xpc_data_get_bytes_ptr(validation), length, kOCFAllocatorNull
            );
            OCFDictionaryRef expected =
                OCFPropertyListCreateWithData(kOCFAllocatorSystemDefault, data, 0, NULL, &parseError);
            if (expected == NULL || OCFGetTypeID(expected) != kDictionaryTypeID) {
                _OCFSetTSD(kLogInProgressSlot, (void *)kOCFBooleanTrue, NULL);
                @try {
                    os_log_error(
                        _CFPrefsClientLog(),
                        "serialized validation data for %{private}@ was not a dictionary plist. Error: "
                        "%{public}@",
                        self,
                        (id)parseError
                    );
                } @finally {
                    _OCFSetTSD(kLogInProgressSlot, NULL, NULL);
                }
                if (parseError != NULL) {
                    OCFRelease(parseError);
                }
            }
            if (data != NULL) {
                OCFRelease(data);
            }
            // CoreFoundation defect (kept): a validation plist that is not a dictionary is logged above and
            // then still passed to CFDictionaryGetCount (0x1c03036f0), which asserts on the wrong type.
            if (expected != NULL) {
                if (OCFDictionaryGetCount(expected) >= 1) {
                    if (dict == NULL) {
                        dict = OCFDictionaryCreateMutable(
                            kOCFAllocatorSystemDefault,
                            0,
                            &kOCFTypeDictionaryKeyCallBacks,
                            &kOCFTypeDictionaryValueCallBacks
                        );
                    }
                    OCFMutableDictionaryRef loaded = dict;
                    void (^applier)(OCFStringRef key, OCFStringRef expectedValue) = ^(
                        OCFStringRef key, OCFStringRef expectedValue
                    ) {
                      if (OCFStringHasPrefix(key, OF_STR("Sig_"))) {
                          return;
                      }
                      OCFTypeRef actual = OCFDictionaryGetValue(loaded, key);
                      if (actual != NULL && OCFEqual(actual, expectedValue)) {
                          return;
                      }
                      OCFStringRef signatureKey = OCFStringCreateWithFormat(
                          kOCFAllocatorSystemDefault, NULL, OF_STR("%s%@"), "Sig_", key
                      );
                      OCFTypeRef signature = OCFDictionaryGetValue(expected, signatureKey);
                      OCFRelease(signatureKey);
                      _OCFSetTSD(kLogInProgressSlot, (void *)kOCFBooleanTrue, NULL);
                      @try {
                          os_log_error(
                              _CFPrefsClientLog(),
                              "%{private}@: Value for key %{public}@ was %{private}@. Expected %{private}@ "
                              "(%{public}@)",
                              self,
                              (id)key,
                              (id)actual,
                              (id)expectedValue,
                              (id)signature
                          );
                      } @finally {
                          _OCFSetTSD(kLogInProgressSlot, NULL, NULL);
                      }
                      OCFDictionarySetValue(loaded, key, expectedValue);
                    };
                    OCFDictionaryApplyFunction(expected, applyDictBlock, applier);
                }
                OCFRelease(expected);
            }
            goto loaded;
        }
    }
fail:
    _OCFSetTSD(kLogInProgressSlot, (void *)kOCFBooleanTrue, NULL);
    @try {
        os_log_error(
            _CFPrefsClientLog(),
            "A RequestNewData response gave an invalid plist. We'll return wrong data this time, but NOT "
            "going "
            "volatile. Sent a request to validate the plist in the daemon and remove it if invalid. "
            "%{private}@",
            self
        );
    } @finally {
        _OCFSetTSD(kLogInProgressSlot, NULL, NULL);
    }
    *error = true;
    if (dict != NULL) {
        OCFRelease(dict);
    }
    return;
loaded:
    if (os_log_type_enabled(_CFPrefsClientLog(), OS_LOG_TYPE_DEBUG)) {
        const char *base;
        if (value != NULL && fd == -1) {
            base = "a new base plist";
        } else if (_dict != NULL) {
            base = "the same base plist";
        } else {
            base = "an empty base plist";
        }
        _OCFSetTSD(kLogInProgressSlot, (void *)kOCFBooleanTrue, NULL);
        @try {
            os_log_debug(
                _CFPrefsClientLog(),
                "%{private}@ loaded: %s and %s",
                self,
                base,
                diff != NULL ? "a diff relative to the base plist"
                             : "no additional changes from the base plist"
            );
        } @finally {
            _OCFSetTSD(kLogInProgressSlot, NULL, NULL);
        }
    }
    if (_dict != NULL) {
        OCFRelease(_dict);
    }
    if (dict != NULL && immutableBase) {
        OCFMutableDictionaryRef copy = OCFDictionaryCreateMutableCopy(kOCFAllocatorSystemDefault, 0, dict);
        OCFRelease(dict);
        dict = copy;
    }
    if (dict != NULL) {
        size_t count = (size_t)OCFDictionaryGetCount(dict);
        if (count >> 60 != 0) {
            OCFStringRef reason = OCFStringCreateWithFormat(
                NULL,
                NULL,
                OF_STR(
                    "*** attempt to create a temporary id buffer which is too large or with a negative count "
                    "(%lu) -- possibly data is corrupt"
                ),
                count
            );
            id exception = ((id (*)(id, SEL, id, id, id))objc_msgSend)(
                (id)exceptionClass,
                sel_getUid("exceptionWithName:reason:userInfo:"),
                (id)ONSGenericException,
                (id)reason,
                nil
            );
            OCFRelease(reason);
            objc_exception_throw(exception);
        }
        size_t bufferCount = count > 1 ? count : 1;
        const void *stackBuffer[count < 0x101 ? bufferCount : 1];
        size_t allocatedSize = 0;
        const void **storage = NULL;
        const void **keys = stackBuffer;
        if (count >= 0x101) {
            keys = _OCFCreateArrayStorage(bufferCount, false, &allocatedSize);
            storage = keys;
        }
        OCFDictionaryGetKeysAndValues(dict, keys, NULL);
        for (; count != 0; --count) {
            if (![self validateValue:NULL forKey:*keys inDict:dict forWriting:NO]) {
                OCFDictionaryRemoveValue(dict, *keys);
            }
            ++keys;
        }
        free(storage);
    }
    _dict = dict;
    __atomic_fetch_add(&_generationCount, 1, __ATOMIC_SEQ_CST);
}

// Native _plistSizeIsAppropriateToRead, 0x1c0303ebc, with .cold.1 (0x1c0318d50, the dispatch_once), .cold.2
// and .cold.3 (0x1c0318d64 and 0x1c0318d90, the error logs, with OUTLINED_FUNCTION_0_64, _1_46 and _8_12)
// and ____plistSizeIsAppropriateToRead_block_invoke (0x1c0305548, the global block
// ___block_literal_global.264). Non-external natively; hidden here (declared in
// Preferences/OCFPrefsPlistSource.h). A size outside 1 through LONG_MAX - 1 is invalid. Once, the process is
// size-limited when its name is localizationswitcherd (the statics .isSizeLimitedProcess and .onceToken,
// __DATA,__bss 0x22e6d3e20 and 0x22e6d3e28); such a process refuses 4 MiB or more. Refusals are logged as
// errors with the log-in-progress slot set (cleared in a
// @finally; region bounds inferred, confidence medium).
bool _plistSizeIsAppropriateToRead(long size) {
    static bool isSizeLimitedProcess;
    static dispatch_once_t onceToken;
    if (size <= 0 || size == LONG_MAX) {
        _OCFSetTSD(kLogInProgressSlot, (void *)kOCFBooleanTrue, NULL);
        @try {
            os_log_error(_CFPrefsClientLog(), "plist had invalid size: %zu.", (size_t)size);
        } @finally {
            _OCFSetTSD(kLogInProgressSlot, NULL, NULL);
        }
        return false;
    }
    dispatch_once(&onceToken, ^{
      if (OCFEqual(_CFProcessNameString(), OF_STR("localizationswitcherd"))) {
          isSizeLimitedProcess = true;
      }
    });
    if ((unsigned long)size >= 0x400000 && isSizeLimitedProcess) {
        _OCFSetTSD(kLogInProgressSlot, (void *)kOCFBooleanTrue, NULL);
        @try {
            os_log_error(
                _CFPrefsClientLog(), "plist is too large to deserialize in this process: %zu.", (size_t)size
            );
        } @finally {
            _OCFSetTSD(kLogInProgressSlot, NULL, NULL);
        }
        return false;
    }
    return true;
}

