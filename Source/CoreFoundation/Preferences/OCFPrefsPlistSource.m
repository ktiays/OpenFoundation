// Native -[CFPrefsPlistSource sendRequestNewDataMessage:toConnection:retryCount:error:], 0x1c030265c, with
// ___78-[CFPrefsPlistSource sendRequestNewDataMessage:toConnection:retryCount:error:]_block_invoke
// (0x1c03041ec). Direct method. A NULL message sets *error. Otherwise the access token (read access) is
// attached; failure sets *error and stops. An activity ("Loading Preferences From Direct CFPrefsD" or "...
// From User Session CFPrefsD") is entered, the PID impersonation added, and the message sent synchronously
// inside the waiting marker of the direct or user daemon (the reply kept in a __block variable). The reply is
// handled, released, the activity released and then left.
// Folds the compiler-outlined pieces ___Block_byref_object_copy__9 (0x1c0302a28),
// ___Block_byref_object_dispose__9 (0x1c0302a38).
- (void)sendRequestNewDataMessage:(xpc_object_t)message
                     toConnection:(xpc_connection_t)connection
                       retryCount:(int)retryCount
                            error:(bool *)error {
    if (message == NULL) {
        *error = true;
        return;
    }
    BOOL attached = [self attachAccessTokenToMessage:message accessType:0];
    *error = !attached;
    if (!attached) {
        return;
    }
    const char *description = (__atomic_load_n(&_directMode, __ATOMIC_ACQUIRE) || _OCFPrefsDirectMode())
                                  ? "Loading Preferences From Direct CFPrefsD"
                                  : "Loading Preferences From User Session CFPrefsD";
    os_activity_t activity = _os_activity_create(
        (void *)&__dso_handle, description, OS_ACTIVITY_CURRENT, OS_ACTIVITY_FLAG_DEFAULT
    );
    struct os_activity_scope_state_s state = {{0, 0}};
    os_activity_scope_enter(activity, &state);
    [self addPIDImpersonationIfNecessary:message];
    __block xpc_object_t reply = NULL;
    void (^send)(void) = ^{
      reply = xpc_connection_send_message_with_reply_sync(connection, message);
    };
    if (__atomic_load_n(&_directMode, __ATOMIC_ACQUIRE) || _OCFPrefsDirectMode()) {
        CFPREFERENCES_IS_WAITING_FOR_DIRECT_CFPREFSD(_containingPreferences, send);
    } else {
        CFPREFERENCES_IS_WAITING_FOR_USER_CFPREFSD(_containingPreferences, send);
    }
    [self handleReply:reply
        toRequestNewDataMessage:message
                   onConnection:connection
                     retryCount:retryCount
                          error:error];
    xpc_release(reply);
    [(id)activity release];
    os_activity_scope_leave(&state);
}

// Native -[CFPrefsPlistSource createRequestNewContentMessageForDaemon:], 0x1c030287c, with
// ___62-[CFPrefsPlistSource createRequestNewContentMessageForDaemon:]_block_invoke (0x1c0302a44) and its
// .cold.1 (0x1c0318ae8). The lock is asserted owned. Only for this source's own role, and only when the data
// are stale (alreadylocked_requestNewDataIfStale's test, inlined with this block), the block runs: unless
// the source volatilizes for an invalid home directory, a synchronize message is created into the __block
// result and, when the read access token attaches, the PID impersonation is added. Answers the message (+1)
// or NULL.
- (xpc_object_t)createRequestNewContentMessageForDaemon:(int)role {
