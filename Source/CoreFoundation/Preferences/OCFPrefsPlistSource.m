        __assert_rtn(
            "_approximateSizeOfPlistValue", "CFPrefsPlistSource.m", 2042, "outObjectCounter == NULL"
        );
    }
    if (value == NULL) {
        return 0;
    }
    OCFTypeID typeID = OCFGetTypeID(value);
    __block size_t size = 0;
    if (typeID == 7) {
        OCFIndex length = OCFStringGetLength(value);
        OCFIndex usedBufLen = 0;
        OCFIndex converted =
            OCFStringGetBytes(value, (OCFRange){0, length}, 0x600, 0, false, NULL, 0, &usedBufLen);
        size = (size_t)(length << ((converted == 0 || usedBufLen != length) ? 1 : 0));
        if (outDescription != NULL) {
            *outDescription = OCFStringCreateWithFormat(
                kOCFAllocatorSystemDefault, NULL, OF_STR("string value, approximate encoded size: %ld"), size
            );
        }
    } else if (typeID == 16) {
        if (outDescription != NULL) {
            *outDescription = OF_STR("deleted value");
        }
    } else if (typeID == 18) {
        OCFIndex objectCount = 0;
        OCFIndex *counter = outObjectCounter != NULL ? outObjectCounter : &objectCount;
        CFDictionaryApply(value, ^(const void *key, const void *entry, Boolean *stop) {
          (void)stop;
          size_t keySize = _approximateSizeOfPlistValue(key, NULL, counter);
          size_t entrySize = _approximateSizeOfPlistValue(entry, NULL, counter);
          size = entrySize + keySize + size;
        });
        if (outDescription != NULL) {
            *outDescription = OCFStringCreateWithFormat(
                kOCFAllocatorSystemDefault,
                NULL,
                OF_STR(
                    "dictionary value, count: %ld, total nested objects: %ld, approximate encoded size: %ld"
                ),
                OCFDictionaryGetCount(value),
                objectCount,
                size
            );
        }
    } else if (typeID == 19) {
        OCFIndex objectCount = 0;
        OCFIndex count = OCFArrayGetCount(value);
        OCFIndex *counter = outObjectCounter != NULL ? outObjectCounter : &objectCount;
        CFArrayApply(value, (OCFRange){0, count}, ^(const void *element, bool *stop) {
          (void)stop;
          size += _approximateSizeOfPlistValue(element, NULL, counter);
        });
        if (outDescription != NULL) {
            *outDescription = OCFStringCreateWithFormat(
                kOCFAllocatorSystemDefault,
                NULL,
                OF_STR("array value, count: %ld, tested nested objects: %ld, approximate encoded size: %ld"),
                OCFArrayGetCount(value),
                objectCount,
                size
            );
        }
    } else if (typeID == 20) {
        size = (size_t)OCFDataGetLength(value);
        if (outDescription != NULL) {
            *outDescription = OCFStringCreateWithFormat(
                kOCFAllocatorSystemDefault, NULL, OF_STR("data value, size: %ld"), size
            );
        }
    } else if (typeID == 21) {
        size = 1;
        if (outDescription != NULL) {
            *outDescription = OF_STR("boolean value");
        }
    } else if (typeID == 22) {
        size = (size_t)OCFNumberGetByteSize(value);
        if (outDescription != NULL) {
            *outDescription = OF_STR("number value");
        }
    } else if (typeID == 42) {
        size = 8;
        if (outDescription != NULL) {
            *outDescription = OF_STR("date value");
        }
    }
    if (outObjectCounter != NULL) {
        *outObjectCounter += 1;
    }
    return size;
}

// Native _compareSizes, 0x1c030533c. Non-external. A CFComparatorFunction over sizes stored as pointers:
// equal sizes compare equal, and a larger first size orders first (kCFCompareLessThan).
static OCFComparisonResult _compareSizes(const void *first, const void *second, void *context) {
    (void)context;
    if (first == second) {
        return kOCFCompareEqualTo;
    }
    return (uintptr_t)first < (uintptr_t)second ? kOCFCompareGreaterThan : kOCFCompareLessThan;
}

