// (0x1c03055dc, descriptor 0x2227aa018). Non-external natively; hidden (see
// Preferences/OCFPrefsPlistSource.h). NULL is 0. Otherwise the approximate encoded size (a __block variable)
// by type: a string its length, doubled unless CFStringGetBytes converts the whole string to ASCII (0x600, no
// loss byte, no buffer) with as many bytes as characters; a data its length; a boolean 1; a number its
// CFNumberGetByteSize; a date 8; a dictionary the sizes of its keys and values (each key, then its value,
// measured with the counter and no description); an array the sizes of its values (over its whole range);
// anything else, including CFNull, 0. The nested measurements count objects into the given counter, or into a
// local one when none is given. With a description out-parameter, a string is stored: created (system default
// allocator) for strings ("string value, approximate encoded size: %ld"), data ("data value, size: %ld"),
// dictionaries ("dictionary value, count: %ld, total nested objects: %ld, approximate encoded size: %ld") and
// arrays ("array value, count: %ld, tested nested objects: %ld, approximate encoded size: %ld", the native
