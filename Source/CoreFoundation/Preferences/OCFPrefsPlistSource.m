// Native -[CFPrefsPlistSource setUserIdentifier:], 0x1c0317654 (with OUTLINED_FUNCTION_25_5, _24_5, _26_4,
// _10_8, _7_13, _2_40 and _3_21). Direct method. A changed user is stored: the any-user and current-user
// constants themselves, NULL, or a copy; the previous user is released. A named user resolves its UID and
// GID through getpwnam (the name as at most 255 ASCII bytes); a failure is logged as a fault. The constants,
// NULL and unresolvable users store -1 UID and GID.
// Folds the compiler-outlined pieces OUTLINED_FUNCTION_2_40 (0x1c0305640), OUTLINED_FUNCTION_3_21
// (0x1c0305654), OUTLINED_FUNCTION_7_13 (0x1c03056a8), OUTLINED_FUNCTION_10_8 (0x1c03056c4),
// OUTLINED_FUNCTION_24_5 (0x1c0305778), OUTLINED_FUNCTION_25_5 (0x1c0305780), OUTLINED_FUNCTION_26_4
// (0x1c030578c).
- (void)setUserIdentifier:(OCFStringRef)user {
    OCFStringRef previous = userIdentifier;
    if (previous == user) {
        return;
    }
    if (user != NULL) {
        if (OCFEqual(user, kOCFPreferencesAnyUser)) {
            userIdentifier = kOCFPreferencesAnyUser;
        } else if (OCFEqual(user, kOCFPreferencesCurrentUser)) {
            userIdentifier = kOCFPreferencesCurrentUser;
        } else {
            userIdentifier = OCFStringCreateCopy(kOCFAllocatorSystemDefault, user);
        }
    } else {
        userIdentifier = NULL;
    }
    if (previous != NULL) {
        OCFRelease(previous);
    }
    if (userIdentifier != NULL && !OCFEqual(userIdentifier, kOCFPreferencesAnyUser) &&
        !OCFEqual(userIdentifier, kOCFPreferencesCurrentUser)) {
