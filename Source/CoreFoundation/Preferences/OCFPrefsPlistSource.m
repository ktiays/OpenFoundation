        void (^create)(void) = ^{
          if (![self volatilizeIfInvalidHomeDir]) {
              message = [self createSynchronizeMessage];
              if (message != NULL && [self attachAccessTokenToMessage:message accessType:0]) {
                  [self addPIDImpersonationIfNecessary:message];
              }
          }
        };
        if (!__atomic_load_n(&_volatile, __ATOMIC_ACQUIRE)) {
            uint32_t *entry = __atomic_load_n(&shmemEntry, __ATOMIC_ACQUIRE);
