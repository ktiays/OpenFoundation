            struct passwd *entry = getpwnam(buffer);
            if (entry != NULL) {
                userUID = entry->pw_uid;
                userGID = entry->pw_gid;
                return;
            }
        }
        os_log_fault(_CFPrefsClientLog(), "Could not resolve UID for user \"%{public}s\".", buffer);
    }
    userUID = (uint32_t)-1;
    userGID = (uint32_t)-1;
}

