// Native __CFToMacSymbol, 0x1c022f738. Non-external. Units up to 0x1f map to themselves. With at least two
// units and a second unit U+F870-U+F87F, U+00AE, U+00A9 and U+2122 followed by U+F87F become 0xe2, 0xe3 and
// 0xe4 and consume two units; those three bases with another variant selector skip the range test and are
// searched alone. Otherwise units with a high byte above 0xf8 fail before the search.
uint32_t __CFToMacSymbol(uint32_t flags, const uint16_t *characters, OCFIndex numChars, uint8_t *byte) {
    (void)flags;
    uint16_t character = characters[0];
    if (character <= 0x1f) {
        *byte = (uint8_t)character;
        return 1;
    }
    bool skipsRangeTest = false;
    if (numChars >= 2) {
        uint16_t next = characters[1];
        if ((next & 0xfff0) == 0xf870) {
            uint8_t variantByte = 0;
            if (character == 0xa9) {
                variantByte = 0xe3;
            } else if (character == 0x2122) {
                variantByte = 0xe4;
            } else if (character == 0xae) {
                variantByte = 0xe2;
            }
            if (variantByte != 0) {
                if (next == 0xf87f) {
                    *byte = variantByte;
                    return 2;
                }
                skipsRangeTest = true;
            }
        }
    }
    if (!skipsRangeTest && (character >> 8) > 0xf8) {
        return 0;
    }
    int low = 0;
    int high = 187;
    do {
        int middle = low + ((high - low) >> 1);
        uint32_t key = MacSymbol_from_uni[middle][0];
        if (character >= key) {
            if (character <= key) {
                *byte = (uint8_t)MacSymbol_from_uni[middle][1];
                return 1;
            }
            low = middle + 1;
        } else {
            high = middle - 1;
        }
    } while (low <= high);
    return 0;
}

// Native __CFFromMacSymbol, 0x1c022f824. Non-external. Bytes 0x22, 0x24, 0x27, 0x2a and 0x2d map to U+2200,
// U+2203, U+220D, U+2217 and U+2212, other bytes up to 0x3f to themselves; 0x40-0x7e and 0xa0-0xdf map
// through their tables without a U+FFFD test, and 0x7f-0x9f fail without a store. From 0xe0 the table unit is
// stored first; 0xff then fails, and 0xe2-0xe4 overwrite the first two output units with their decomposition
// pair in one 32-bit store (the copy below) and return 2, or 1 when flag bit 0x200 is set. The result is the
// count masked to 16 bits (AND W0, W8, #0xffff).
uint32_t __CFFromMacSymbol(uint32_t flags, uint8_t byte, uint16_t *characters) {
    if (byte <= 0x3f) {
        uint16_t value;
        switch (byte) {
            case 0x22:
                value = 0x2200;
                break;
            case 0x24:
                value = 0x2203;
                break;
            case 0x27:
                value = 0x220d;
                break;
            case 0x2a:
                value = 0x2217;
                break;
            case 0x2d:
                value = 0x2212;
                break;
            default:
                value = byte;
                break;
        }
        *characters = value;
        return 1;
    }
    if (byte <= 0x7e) {
        *characters = MacSymbol_to_uni_to7E[byte - 0x40];
        return 1;
    }
    if (byte < 0xa0) {
        return 0;
    }
    if (byte <= 0xdf) {
        *characters = MacSymbol_to_uni_toDF[byte - 0xa0];
        return 1;
    }
    uint16_t value = MacSymbol_to_uni_toFF[byte - 0xe0];
    *characters = value;
    if (byte - 0xe0 == 0x1f) {
        return 0;
    }
    if ((uint32_t)byte - 0xe2 > 2) {
        return 1;
    }
    memcpy(characters, __CFMacSymbolTwoCharDecompSeqTable[value], sizeof(uint16_t) * 2);
    return (flags & 0x200) == 0 ? 2 : 1;
}

