// Native __CFPrecomposeCharMacSymbol, 0x1c022f984. Non-external. Evidence:
// Local/Evidence/cf-core/iphone-simulator-core-corpus.json. Fewer than two characters (signed) or a second
// unit other than U+0338 answer 0. Otherwise, with a nonzero maxByteLen, '=' stores 0xb9, U+2282 0xcb and
// U+2208 0xcf (any other first unit stores nothing); in every case usedByteLen becomes 1 and the result is 2.
// The flags are not read.
OCFIndex __CFPrecomposeCharMacSymbol(
    uint32_t flags,
    const uint16_t *character,
    OCFIndex numChars,
    uint8_t *bytes,
    OCFIndex maxByteLen,
    OCFIndex *usedByteLen
) {
    (void)flags;
    if (numChars < 2 || character[1] != 0x338) {
        return 0;
    }
    if (maxByteLen != 0) {
        uint16_t base = character[0];
        if (base == '=') {
            *bytes = 0xB9;
        } else if (base == 0x2282) {
            *bytes = 0xCB;
        } else if (base == 0x2208) {
            *bytes = 0xCF;
        }
    }
    *usedByteLen = 1;
    return 2;
}

