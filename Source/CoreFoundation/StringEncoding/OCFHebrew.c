// Native __CFFromWindowsHebrew, 0x1c0231be8. Non-external.
uint32_t __CFFromWindowsHebrew(uint32_t flags, uint8_t byte, uint16_t *character) {
    (void)flags;
    uint16_t value = byte;
    if ((byte & 0x80) != 0) {
        value = WindowsHebrew_to_uni[byte & 0x7f];
    }
    *character = value;
    return value != 0xfffd;
}

