// Native __CFToISOLatinHebrew, 0x1c0231a98. Non-external.
uint32_t __CFToISOLatinHebrew(uint32_t flags, uint16_t character, uint8_t *byte) {
    (void)flags;
    if (character <= 0xa0) {
        *byte = (uint8_t)character;
        return 1;
    }
    if (character == 0xa1 || character > 0x203e) {
        return 0;
    }
    int low = 0;
    int high = 56;
    do {
        int middle = low + ((high - low) >> 1);
        uint32_t entry = ISOLatinHebrew_from_uni[middle][0];
        if (character >= entry) {
            if (character <= entry) {
                *byte = (uint8_t)ISOLatinHebrew_from_uni[middle][1];
                return 1;
            }
            low = middle + 1;
        } else {
            high = middle - 1;
        }
    } while (low <= high);
    return 0;
}

// Native __CFFromISOLatinHebrew, 0x1c0231b14. Non-external. Bytes 0xa1-0xbe and 0xdf-0xfa use the two tables;
// 0xbf-0xde and 0xfb-0xff decode to U+FFFD and fail.
uint32_t __CFFromISOLatinHebrew(uint32_t flags, uint8_t byte, uint16_t *character) {
    (void)flags;
    uint16_t value = byte;
    if (byte > 0xa0) {
        if (byte <= 0xbe) {
            value = ISOLatinHebrew_to_uni[byte - 0xa1];
        } else if ((uint32_t)byte - 0xfb >= 0xffffffe4u) {
            value = ISOLatinHebrew_to_uni2[byte - 0xdf];
        } else {
            value = 0xfffd;
        }
    }
    *character = value;
    return value != 0xfffd;
}

